const TRADITIONS = Object.keys(DEFS);

// ── public API ──────────────────────────────────────────────────────────────
const yearCache = new Map(); // "tradition:year" -> festivals[]

function getYear(tradition, year) {
    const key = `${tradition}:${year}`;
    if (!yearCache.has(key)) {
        yearCache.set(key, computeYear(DEFS[tradition], year).map(fest => ({
            id: `${tradition}-${fest.key}-${fest.date}`,
            name: fest.name,
            date: fest.date,
            description: fest.description,
            fasting: false,
            tags: [],
            category: 'Regional',
            type: 'regional',
            tradition,
        })));
    }
    return yearCache.get(key);
}

function getRegionalFestivals(tradition, year, month) {
    const all = getYear(tradition, year);
    if (!month) return all;
    const prefix = `${year}-${String(month).padStart(2, '0')}-`;
    return all.filter(f => f.date.startsWith(prefix));
}


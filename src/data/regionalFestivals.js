// Festival definitions for each regional calendar tradition.
//
// Only *rules* are stored (which lunar month / tithi / solar month /
// nakshatra) — dates are computed per year by utils/regionalFestivalEngine.js,
// so the calendar keeps working for 2027, 2028 … with no data entry.
//
// Conventions
//   • Lunar months are AMANTA (new-moon to new-moon), as used by the Telugu,
//     Kannada, Marathi, Gujarati and Odia calendars. Purnimanta names used in
//     North India differ for the dark fortnight — every rule below is written
//     in amanta terms.
//   • Tithi number k: 1–14 Shukla, 15 = Purnima, 16–29 Krishna (16 = Krishna
//     Pratipada … 23 = Krishna Ashtami), 30 = Amavasya.
//   • Solar signs: 0 Mesha … 3 Karka, 4 Simha, 5 Kanya, 6 Tula, 7 Vrischika,
//     8 Dhanu, 9 Makara, 10 Kumbha, 11 Meena.
//   • Nakshatra index: 0 Ashwini … 2 Krittika, 5 Ardra, 7 Pushya, 9 Magha,
//     10 Purva Phalguni, 11 Uttara Phalguni, 12 Hasta, 15 Vishakha,
//     20 Uttara Ashadha, 21 Shravana, 22 Dhanishta, 23 Shatabhisha.

